const dictionaries = { en, ja } as const;
export type AdminLocale = keyof typeof dictionaries;

/** Admin strings for the locale in the URL (/:locale/admin/...). */
export function useAdminT(): { s: AdminStrings; locale: AdminLocale; prefix: string } {
  const { locale: raw } = useParams<{ locale: string }>();
  const locale: AdminLocale = raw === 'ja' ? 'ja' : 'en';
  return { s: dictionaries[locale], locale, prefix: `/${locale}/admin` };
}
